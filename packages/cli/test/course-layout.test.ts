import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { parse } from "yaml";
import { expect, it, onTestFinished, vi } from "vitest";
import { add } from "../src/commands/add";
import { kata } from "../src/commands/kata";
import { readCatalog, readDojoRc, resolveAllKatas, writeDojoRc } from "../src/config";

it("installs two chapter courses visibly, runs their actual lesson checks and saves independent YAML progress", async () => {
  const directory = mkdtempSync(resolve(tmpdir(), "dojo-course-layout-"));
  const root = resolve(directory, "learning");
  mkdirSync(root);
  vi.stubEnv("DOJOFOO_HOME", resolve(directory, "private"));
  onTestFinished(() => { vi.unstubAllEnvs(); rmSync(directory, { recursive: true, force: true }); });
  for (const id of ["first", "second"]) {
    const source = resolve(directory, id);
    const lesson = resolve(source, "chapters/01/lessons/01");
    mkdirSync(lesson, { recursive: true });
    writeFileSync(resolve(source, "dojo.yaml"), `name: ${id}\nversion: 1.0.0\ndescription: Practice\ntest: node {template}\nrunner:\n  adapter: exit-code\nchapters:\n  - id: foundations\n    title: Foundations\n    path: chapters/01\n    lessons:\n      - id: start\n        title: Start\n        template: chapters/01/lessons/01/kata.cjs\n`);
    writeFileSync(resolve(source, "DOJO.md"), "Teach the learner.");
    writeFileSync(resolve(lesson, "SENSEI.md"), "Help without giving the edit.");
    writeFileSync(resolve(lesson, "README.md"), "Double the supplied number.");
    writeFileSync(resolve(lesson, "kata.cjs"), "exports.double = () => { throw Error('Not implemented'); };\n");
    writeFileSync(resolve(lesson, "kata.test.cjs"), "require('node:assert/strict').equal(require('./kata.cjs').double(3), 6);\n");
    mkdirSync(resolve(source, ".dojo/sensei"), { recursive: true });
    writeFileSync(resolve(source, ".dojo/sensei/instructions.md"), `Teach ${id}.`);
    mkdirSync(resolve(source, ".dojo/kyoshi"), { recursive: true });
    writeFileSync(resolve(source, ".dojo/kyoshi/instructions.md"), "PRIVATE AUTHORING");
    await add(root, [source]);
    expect(readFileSync(resolve(root, "courses", id, ".dojo/sensei/instructions.md"), "utf8")).toBe(`Teach ${id}.`);
    expect(existsSync(resolve(root, "courses", id, ".dojo/kyoshi"))).toBe(false);
  }
  expect(existsSync(resolve(root, "package.json"))).toBe(false);
  expect(existsSync(resolve(root, ".dojos"))).toBe(false);
  expect(existsSync(resolve(root, ".dojorc"))).toBe(false);
  const rc = readDojoRc(root);
  rc.currentDojo = "first";
  rc.currentKata = "start";
  writeDojoRc(root, rc);
  const selected = resolveAllKatas(root, readDojoRc(root), readCatalog(root, "first"))[0]!;
  expect(selected.workspacePath).toBe(resolve(root, "courses/first/chapters/01/lessons/01/kata.cjs"));
  writeFileSync(selected.workspacePath, "exports.double = value => value * 2;\n");
  kata(root, ["--check", "--reporter=json"]);
  const first = parse(readFileSync(resolve(root, "courses/first/dojo.yaml"), "utf8"));
  expect(first.progress.lessons.start.status).toBe("completed");
  const second = parse(readFileSync(resolve(root, "courses/second/dojo.yaml"), "utf8"));
  expect(second.progress?.lessons?.start?.status).not.toBe("completed");
  expect(readFileSync(resolve(root, "courses/second/chapters/01/lessons/01/kata.cjs"), "utf8")).toContain("Not implemented");
  await expect(add(root, [resolve(directory, "first"), "--force"])).rejects.toThrow("preserve your files");
  expect(readFileSync(selected.workspacePath, "utf8")).toContain("value * 2");
  expect(parse(readFileSync(resolve(root, "courses/first/dojo.yaml"), "utf8")).progress.lessons.start.status).toBe("completed");
  const progress = readDojoRc(root);
  progress.currentDojo = "second";
  progress.currentKata = "start";
  progress.progress!.second!.completed = ["start"];
  writeDojoRc(root, progress);
  await add(root, [resolve(directory, "second"), "--force"]);
  expect(parse(readFileSync(resolve(root, "courses/second/dojo.yaml"), "utf8")).progress.lessons.start.status).toBe("completed");
  const localEnvironment = resolve(root, "courses/second/.env.local");
  writeFileSync(localEnvironment, "LOCAL_FIXTURE=preserve-me\n");
  await expect(add(root, [resolve(directory, "second"), "--force"])).rejects.toThrow("preserve your files");
  expect(readFileSync(localEnvironment, "utf8")).toBe("LOCAL_FIXTURE=preserve-me\n");
});
