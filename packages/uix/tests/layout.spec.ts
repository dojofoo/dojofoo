import { expect, test } from "@playwright/test";

for (const story of ["learner-kata", "course-authoring"]) {
  test(`${story} keeps sidebar fixed and resizes chat without remounting the editor`, async ({ page }, testInfo) => {
    await page.goto(`/iframe.html?id=pages-dojo--${story}&viewMode=story`);
    const code = page.getByRole("textbox", { name: "Code editor", exact: true });
    await code.focus();
    await page.keyboard.press("ControlOrMeta+End");
    await page.keyboard.type("\n// kept while resizing");
    const width = (selector: string) => page.locator(selector).evaluate(element => element.getBoundingClientRect().width);
    const sidebar = page.getByRole("separator", { name: "Sidebar", exact: true });
    const before = await width(".ui-as-side");
    await expect(sidebar).toHaveCount(0);
    const sideBounds = (await page.locator(".ui-as-side").boundingBox())!;
    await page.mouse.move(sideBounds.x + sideBounds.width, sideBounds.y + 300);
    await page.mouse.down();
    await page.mouse.move(sideBounds.x + sideBounds.width + 100, sideBounds.y + 300, { steps: 10 });
    await page.mouse.up();
    expect(await width(".ui-as-side")).toBe(before);
    const chatWidth = await width(".ui-as-aside");
    const divider = page.getByRole("separator", { name: "Editor", exact: true });
    await divider.focus();
    await divider.press("Shift+ArrowLeft");
    await expect.poll(() => width(".ui-as-aside")).toBeGreaterThan(chatWidth + 40);
    await expect(page.locator(".view-lines")).toContainText("// kept while resizing");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click();
    await expect.poll(() => width(".ui-as-side")).toBe(64);
    await expect(sidebar).toBeHidden();
    await page.getByRole("button", { name: "Expand sidebar", exact: true }).click();
    await expect.poll(() => width(".ui-as-side")).toBe(before);
    const editorWidth = await width(".ui-as-chat__ide");
    await page.getByRole("button", { name: "Show settings", exact: true }).click();
    await expect.poll(async () => Math.abs(await width(".ui-as-chat__ide") - editorWidth)).toBeLessThan(8);
    await expect(divider).toBeVisible();
    await page.getByRole("button", { name: "Hide settings", exact: true }).click();
    await expect(divider).toBeVisible();
    await expect(page.getByRole("region", { name: "Course conversation", exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("resized-workspace.png") });
    await expect.poll(async () => Math.abs(await width(".ui-as-side") - before)).toBeLessThan(1);
    await divider.dblclick();
    await expect(page.locator(".view-lines")).toContainText("// kept while resizing");
  });
}

for (const story of ["learner-kata", "course-authoring"]) test(`${story} shares the resized width between chat and settings and restores hidden chat`, async ({ page }, testInfo) => {
  await page.goto(`/iframe.html?id=pages-dojo--${story}&viewMode=story`);
  const message = page.getByRole("textbox", { name: "Message", exact: true });
  await message.fill("Keep this chat draft");
  const code = page.getByRole("textbox", { name: "Code editor", exact: true });
  await code.focus();
  await page.keyboard.press("ControlOrMeta+End");
  await page.keyboard.type("\n// kept through chat toggles");
  const pane = page.locator(".ui-as-conversation-pane");
  const width = () => pane.evaluate(element => element.getBoundingClientRect().width);
  const divider = page.getByRole("separator", { name: "Editor", exact: true });
  const original = await width();
  const bounds = (await divider.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x - 130, bounds.y + bounds.height / 2, { steps: 10 });
  await page.mouse.up();
  await expect.poll(width).toBeGreaterThan(original + 100);
  await expect(pane).not.toHaveAttribute("data-free");
  // Motion batches flex-grow writes into the next animation frame, including reduced motion.
  await pane.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  const resized = await width();
  const chatX = (await pane.boundingBox())!.x;
  await page.getByRole("button", { name: "Show settings", exact: true }).click();
  const settings = page.getByRole("complementary", { name: "Settings", exact: true });
  await expect(settings).toBeVisible();
  await expect.poll(async () => Math.abs(await width() - resized)).toBeLessThan(1);
  await expect.poll(async () => Math.abs((await settings.boundingBox())!.x - chatX)).toBeLessThan(1);
  await expect(divider).toBeVisible();
  await divider.focus();
  await divider.press("Shift+ArrowLeft");
  await expect.poll(width).toBeGreaterThan(resized + 40);
  await expect(divider).toHaveCSS("outline-color", await divider.evaluate(element => getComputedStyle(element).backgroundColor));
  const settingsWidth = await width();
  await page.screenshot({ path: testInfo.outputPath("shared-settings-pane.png") });
  await page.getByRole("button", { name: "Close settings", exact: true }).click();
  await expect(page.getByRole("region", { name: "Course conversation", exact: true })).toBeVisible();
  await expect.poll(async () => Math.abs(await width() - settingsWidth)).toBeLessThan(1);
  const editorWidth = (await page.locator(".ui-as-main").boundingBox())!.width;
  await page.getByRole("button", { name: "Hide chat", exact: true }).click();
  await expect(page.getByRole("region", { name: "Course conversation", exact: true })).toBeHidden();
  await expect(divider).toBeHidden();
  await expect.poll(async () => (await page.locator(".ui-as-main").boundingBox())!.width).toBeGreaterThan(editorWidth + 100);
  const frameGap = await page.locator(".ui-as-app").evaluate(element => parseFloat(getComputedStyle(element).getPropertyValue("--frame-gap")));
  await expect.poll(async () => {
    const app = (await page.locator(".ui-as-app").boundingBox())!;
    const main = (await page.locator(".ui-as-main").boundingBox())!;
    return Math.abs(app.x + app.width - main.x - main.width - frameGap);
  }).toBeLessThan(1);
  await page.screenshot({ path: testInfo.outputPath("collapsed-chat-margin.png") });
  await page.getByRole("button", { name: "Show chat", exact: true }).click();
  await expect(page.getByRole("region", { name: "Course conversation", exact: true })).toBeVisible();
  await expect.poll(async () => Math.abs(await width() - settingsWidth)).toBeLessThan(1);
  await page.getByRole("button", { name: "Close chat", exact: true }).click();
  await page.getByRole("button", { name: "Show settings", exact: true }).click();
  await expect(settings).toBeVisible();
  await expect.poll(async () => Math.abs(await width() - settingsWidth)).toBeLessThan(1);
  await page.getByRole("button", { name: "Close settings", exact: true }).click();
  await expect(page.getByRole("region", { name: "Course conversation", exact: true })).toBeHidden();
  await page.getByRole("button", { name: "Show chat", exact: true }).click();
  await expect.poll(async () => Math.abs(await width() - settingsWidth)).toBeLessThan(1);
  await expect(page.locator(".view-lines")).toContainText("// kept through chat toggles");
  await expect(message).toHaveValue("Keep this chat draft");
});

test("narrow drawers keep working across the desktop breakpoint", async ({ page }, testInfo) => {
  await page.goto("/iframe.html?id=pages-dojo--learner-kata&viewMode=story");
  const code = page.getByRole("textbox", { name: "Code editor", exact: true });
  await code.focus();
  await page.keyboard.press("ControlOrMeta+End");
  await page.keyboard.type("\n// kept across breakpoint");
  await page.setViewportSize({ width: 760, height: 900 });
  await expect(page.getByRole("separator")).toHaveCount(0);
  await page.getByRole("button", { name: "Open sidebar", exact: true }).click();
  await expect(page.getByRole("button", { name: "Close sidebar", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Close sidebar", exact: true }).click();
  await page.getByRole("button", { name: "Show chat", exact: true }).click();
  await expect(page.getByRole("region", { name: "Course conversation", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("narrow-conversation.png") });
  await page.getByRole("button", { name: "Close chat", exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect(page.getByRole("separator")).toHaveCount(1);
  await expect(page.locator(".view-lines")).toContainText("// kept across breakpoint");
});

