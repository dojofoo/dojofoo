import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { generateFilesOnly } from "fumadocs-openapi";
import { openapi, apiPageOptions } from "../src/lib/openapi.server";

const folder = resolve(import.meta.dirname, "../content/docs/api");
const check = process.argv.includes("--check");
const generated = await generateFilesOnly({ input: openapi, ...apiPageOptions });
const source = await openapi.staticSource(apiPageOptions);
const docs = Object.fromEntries(Object.entries(await openapi.getSchemas()).map(([id, schema]) => [id, schema.bundled]));
const pages = Object.fromEntries(source.files.filter(file => file.type === "page").map(file => {
  const { payload, ...props } = file.data.getOpenAPIPageProps();
  return [file.path.replace(/^\//, "").replace(/\.mdx$/, ""), props];
}));
// Each page's operation, its path under the API's base (/api/v1) as the sidebar shows it: "GET /health"
const spec = docs.course as { tags?: { name: string }[]; paths: Record<string, Record<string, { tags?: string[] }>> };
const base = "/api/v1";
const operations = Object.entries(pages).map(([name, props]) => {
  const { path, method } = (props as { operations: { path: string; method: string }[] }).operations[0];
  return { name, method, route: path.slice(base.length), tag: spec.paths[path][method].tags?.[0] ?? "Other" };
});
const outputs = new Map(generated.map(file => {
  const name = file.path.replace(/^\//, "");
  const operation = operations.find(item => `${item.name}.mdx` === name);
  const content = operation ? file.content.replace("\n_openapi:\n", `\n_openapi:\n  route: ${operation.route}\n`) : file.content;
  return [name, `${content.trimEnd()}\n`];
}));
outputs.set("../../../src/generated/course-api.json", `${JSON.stringify({ preloaded: { docs }, pages }, null, 2)}\n`);
// The collections as the spec orders its tags, each one's routes as a path tree – the collection's own first, then by
// path, its parameters after the fixed segments – and its methods in CRUD order
const methods = ["get", "post", "put", "patch", "delete"];
const collection = (tag: string) => `/${tag.toLowerCase().replace(/\s+/g, "-")}`;
const tags = [...new Set([...(spec.tags ?? []).map(tag => tag.name), ...operations.map(item => item.tag)])];
outputs.set("meta.json", `${JSON.stringify({ title: "API", pages: ["index", ...tags.flatMap(tag => {
  const items = operations.filter(item => item.tag === tag).sort((a, b) => {
    const own = Number(!a.route.startsWith(collection(tag))) - Number(!b.route.startsWith(collection(tag)));
    const [x, y] = [a.route.replaceAll("{", "~"), b.route.replaceAll("{", "~")];
    return own || (x < y ? -1 : x > y ? 1 : 0) || methods.indexOf(a.method) - methods.indexOf(b.method);
  });
  return items.length ? [`---${tag}---`, ...items.map(item => item.name)] : [];
})] }, null, 2)}\n`);
for (const name of await readdir(folder)) {
  if (!name.endsWith(".mdx") || name === "index.mdx" || outputs.has(name)) continue;
  const contents = await readFile(resolve(folder, name), "utf8");
  if (!contents.includes("Generated by apps/api/scripts/generate-openapi.ts.") && !contents.includes("generated by Fumadocs")) continue;
  if (check) throw new Error(`Stale generated API page: ${name}`);
  await rm(resolve(folder, name));
}
for (const [name, content] of outputs) {
  const path = resolve(folder, name);
  if (check) {
    if (await readFile(path, "utf8").catch(() => "") !== content) throw new Error(`${name} is stale. Run openapi:generate.`);
  } else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, content); }
}
console.log(`${check ? "Verified" : "Generated"} ${Object.keys(pages).length} Fumadocs OpenAPI pages and their prepared data.`);
